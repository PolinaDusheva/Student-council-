// КОНВЕНЦИИ НА EF CORE (по подразбиране, без допълнителна конфигурация):
//   - Свойство "Id" (или "MemberId") автоматично се разпознава като
//     PRIMARY KEY и се генерира автоматично (AUTOINCREMENT).
//   - Тип "string" се превежда до TEXT в SQLite / NVARCHAR в SQL Server.
//   - Тип "int" се превежда до INTEGER.
//   - Тип "DateTime" се превежда до TEXT (ISO 8601) в SQLite.
// ============================================================

namespace StudentCouncil.Models;

public class Member
{
    // Id е първичен ключ (PRIMARY KEY) на таблицата.
    // EF Core го разпознава по конвенция — не е нужен атрибут [Key].
    // При добавяне на нов Member, базата автоматично присвоява следващото
    // число (1, 2, 3...). Никога не задаваме Id ръчно при Add().
    public int Id { get; set; }

    // { get; set; } са автоматични свойства (auto-properties).
    // Компилаторът скрито генерира backing поле и getter/setter.
    // Еквивалентно на: private string _name; public string Name { get { return _name; } set { _name = value; } }
    // Но много по-кратко и четимо.

    // = "" е стойност по подразбиране — Name никога не е null.
    // В C# 8+ с Nullable Reference Types, без = "" компилаторът предупреждава
    // за потенциален null. Задаваме "" за да сме сигурни, че полето е
    // инициализирано дори преди да му присвоим стойност.
    public string Name { get; set; } = "";

    // Position пази длъжността: "Председател", "Секретар", "Член" и т.н.
    // Стойността се задава при seed в Program.cs или от потребителя в UI.
    public string Position { get; set; } = "";
}
