// КАК СЕ ИЗПОЛЗВА:
//   Задачите се създават от конкретен член (CreatedBy), назначават се
//   на друг член (Assignee) и имат статус, който може да се промени
//   директно от таблицата в UI (inline editing).
//
// ЗАБЕЛЕЖКА ЗА ИМЕНУВАНЕТО:
//   Избягваме "Task" като самостоятелно име, защото System.Threading.Task
//   е вграден тип в .NET за асинхронно програмиране. Добавяме "Project"
//   префикс за яснота.
// ============================================================

namespace StudentCouncil.Models;

public class ProjectTask
{
    // Първичен ключ — генерира се автоматично от базата данни.
    public int Id { get; set; }

    // Описание на задачата — какво трябва да се направи.
    public string Name { get; set; } = "";

    // Кой е създал задачата — пази се като текст (пълно име на члена).
    // Алтернативно би могло да е int CreatedById с Foreign Key към Members,
    // но текстовият вариант е по-прост за начало.
    public string CreatedBy { get; set; } = "";

    // На кого е назначена задачата за изпълнение.
    public string Assignee { get; set; } = "";

    // Статус на задачата — едно от три фиксирани стойности:
    // "За изпълнение" (нова), "В процес" (работи се), "Завършена".
    // Стойността по подразбиране е "За изпълнение" — всяка нова задача
    // започва в опашката за изпълнение.
    // В UI потребителят може да смени статуса директно от падащо меню
    // в таблицата, без да отваря форма за редакция.
    public string Status { get; set; } = "За изпълнение";
}
