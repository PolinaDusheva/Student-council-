namespace StudentCouncil.Models;

public class CouncilEvent
{
    // Първичен ключ — EF Core го генерира автоматично (AUTOINCREMENT).
    public int Id { get; set; }

    // Наименование на събитието. = "" предотвратява null.
    public string Name { get; set; } = "";

    // Физическо местоположение — зала, адрес, онлайн платформа.
    public string Location { get; set; } = "";

    // Кратко описание за участниците.
    public string Description { get; set; } = "";

    // DateTime е структура (value type) в C# — съхранява дата И час.
    // DateTime.Today връща днешната дата с час 00:00:00.
    // AddDays(7) добавя 7 дни — по подразбиране събитието е след седмица.
    // Това е удобна начална стойност за формата за добавяне.
    public DateTime Date { get; set; } = DateTime.Today.AddDays(7);

    // Максимален брой участници — ограничава капацитета.
    // Сравнява се с броя реални записвания от таблица EventAttendees.
    public int MaxParticipants { get; set; } = 30;

    // Организатор — избира се от списъка с членове в UI.
    // Пазим само името (string), не Foreign Key — опростен подход.
    public string Organizer { get; set; } = "";
}
